// Usage: node web/scripts/gen-hu-settlements.mjs <HU.txt> <districts.tsv> > out.sql
// HU.txt: GeoNames postal codes (CC BY 4.0). districts.tsv: district, name, lat, lng.
import { readFileSync } from 'node:fs'

const [, , zipPath, distPath] = process.argv
if (!zipPath || !distPath) {
  console.error('usage: gen-hu-settlements.mjs <HU.txt> <districts.tsv>')
  process.exit(2)
}
const rows = (p) => readFileSync(p, 'utf8').split('\n').map((l) => l.replace(/\r$/, '')).filter(Boolean).map((l) => l.split('\t'))
const r4 = (n) => Math.round(Number(n) * 1e4) / 1e4

// Budapest districts
const dist = new Map()
for (const [d, , lat, lng] of rows(distPath)) {
  const n = Number(d)
  if (!Number.isInteger(n)) continue // header
  if (!(lat >= 47.35 && lat <= 47.62 && lng >= 18.92 && lng <= 19.34)) {
    console.error(`district ${n} outside Budapest bbox`)
    process.exit(1)
  }
  dist.set(n, { lat: r4(lat), lng: r4(lng), pc: new Set() })
}
for (let n = 1; n <= 23; n++) {
  if (!dist.has(n)) {
    console.error(`missing district ${n}`)
    process.exit(1)
  }
}

// Other settlements
const groups = new Map()
for (const c of rows(zipPath)) {
  const [, pc, name, county, , , , , , lat, lng] = c
  if (county === 'Budapest') {
    const xy = Number(pc.slice(1, 3))
    const d = pc === '1007' ? 13 : pc[0] === '1' && xy >= 1 && xy <= 23 ? xy : null
    if (d) dist.get(d).pc.add(pc)
    continue
  }
  const k = `${name}\t${county}`
  let g = groups.get(k)
  if (!g) groups.set(k, (g = { name, county, lat: Number(lat), lng: Number(lng), pc: new Set() }))
  else if (Math.abs(g.lat - lat) > 0.05 || Math.abs(g.lng - lng) > 0.05) console.error(`warning: coordinates differ in ${name}, ${county}`)
  g.pc.add(pc)
}

const out = [...groups.values()].map((g) => ({ name: g.name, county: g.county, district: null, lat: r4(g.lat), lng: r4(g.lng), pc: g.pc }))
for (const [n, d] of dist) out.push({ name: 'Budapest', county: 'Budapest', district: n, lat: d.lat, lng: d.lng, pc: d.pc })
const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0)
out.sort((a, b) => cmp(a.county, b.county) || cmp(a.name, b.name) || (a.district ?? 0) - (b.district ?? 0))

const q = (s) => `'${s.replaceAll("'", "''")}'`
const lines = out.map((s, i) => `(${i + 1},${q(s.name)},${q(s.county)},${s.district ?? 'NULL'},${s.lat},${s.lng},ARRAY[${[...s.pc].sort().map(q).join(',')}])`)
const head = 'INSERT INTO "hu_settlements" ("id","name","county","district","lat","lng","postcodes") VALUES\n'
let sql = `-- Hungarian settlements: GeoNames postal codes (CC BY 4.0, https://www.geonames.org), generated by web/scripts/gen-hu-settlements.mjs on ${new Date().toISOString().slice(0, 10)}.\n`
for (let i = 0; i < lines.length; i += 500) sql += head + lines.slice(i, i + 500).join(',\n') + ';\n'
sql += `SELECT setval(pg_get_serial_sequence('"hu_settlements"','id'), (SELECT MAX("id") FROM "hu_settlements"));\n`
process.stdout.write(sql)

const owner = new Map()
for (const s of out) for (const p of s.pc) owner.set(p, (owner.get(p) ?? 0) + 1)
console.error(`settlements: ${out.length - 23}`)
console.error(`budapest districts: ${dist.size}`)
console.error(`total postcodes: ${owner.size}`)
console.error(`postcodes mapped to 2+ settlements: ${[...owner.values()].filter((v) => v > 1).length}`)
